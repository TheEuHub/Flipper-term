#!/usr/bin/env python3
"""Copy firmware-derived raster assets from the native headers into web/assets.js."""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
fonts = (root / 'device_fonts.h').read_text()
glyphs = re.findall(r'\{\{([\d,]+)\},(\d+)\}', fonts)
if len(glyphs) != 190:
    raise SystemExit('Unexpected font data')
data = [[list(map(int, rows.strip(',').split(','))) + [int(width)]
         for rows, width in glyphs[i:i+95]] for i in (0, 95)]
frames = re.findall(r'0x([0-9a-fA-F]{2})', (root / 'dolphin_frames.h').read_text())
if len(frames) != 3200:
    raise SystemExit('Unexpected dolphin frame data')
waves = [[int(x, 16) for x in frames[i:i+800]] for i in range(0, len(frames), 800)]
out = '// Firmware-derived assets; see README.md and LICENSE. Generated by tools/build_web_assets.py.\n'
out += 'const DEVICE_FONTS = ' + json.dumps(data, separators=(',', ':')) + ';\n'
out += 'const DOLPHIN_FRAMES = ' + json.dumps(waves, separators=(',', ':')) + ';\n'
(root / 'web/assets.js').write_text(out)
